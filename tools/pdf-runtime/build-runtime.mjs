import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: [new URL("entry.ts", import.meta.url).pathname],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["chrome100", "safari15"],
  minify: true,
  legalComments: "inline",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
await writeFile(
  new URL("../../packages/app/src/file-panels/pdf/runtime.gen.ts", import.meta.url),
  `// Generated by build-runtime.mjs; includes PDF.js (Apache-2.0).\nexport const pdfRuntimeScript = ${JSON.stringify(js)};\n`,
);
console.log(`PDF runtime: ${js.length} bytes`);
